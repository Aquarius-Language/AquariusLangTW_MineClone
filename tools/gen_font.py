def main():
    OUT.mkdir(parents=True, exist_ok=True)
    img = np.zeros((6 * CH, 16 * CW, 4), np.uint8)
    for code in range(32, 128):
        rows = G[chr(code)]
        i = code - 32
        cx, cy = (i % 16) * CW, (i // 16) * CH
        for r, line in enumerate(rows):
            for c, ch in enumerate(line):
                if ch == "#":
                    img[cy + 1 + r, cx + 1 + c] = (255, 255, 255, 255)
    (OUT / "font.rgba").write_bytes(img.tobytes())
    Image.fromarray(img).resize((16 * CW * 4, 6 * CH * 4), Image.NEAREST).save(OUT / "font_preview.png")
    print("font atlas", img.shape)


if __name__ == "__main__":
    main()
